test('shot entry counts outcomes once, survives offline reload and clears the alternate scoring source', async ({ page, context }) => {
  test.setTimeout(180000)
  await page.goto('/')
  await performance(page, 'Matches')
  await page.getByRole('button', { name: 'Record match', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('Opponent', { exact: true }).fill('Shot record test')
  await dialog.getByText('Scoring: quick totals or individual shots', { exact: true }).click()
  await dialog.getByRole('button', { name: 'Individual shots', exact: true }).click()
  await dialog.getByLabel('Shot record coverage').selectOption('Complete')
  await dialog.getByRole('button', { name: 'Add shot', exact: true }).click()
  await dialog.getByLabel('Shot 1 type', { exact: true }).selectOption('goal')
  await dialog.getByLabel('Shot 1 outcome', { exact: true }).selectOption('one')
  await dialog.getByRole('button', { name: 'Add shot', exact: true }).click()
  await dialog.getByLabel('Shot 2 type', { exact: true }).selectOption('two')
  await dialog.getByLabel('Shot 2 outcome', { exact: true }).selectOption('two')
  await expect(dialog.getByText('3 points awarded', { exact: true })).toBeVisible()
  await dialog.getByRole('button', { name: 'Save match', exact: true }).click()
  await expect(dialog).not.toBeVisible()
  await expect(page.getByText('3 scoring points', { exact: true })).toBeVisible()
  await page.evaluate(async () => { await navigator.serviceWorker.ready })
  await page.reload(); await page.waitForFunction(() => navigator.serviceWorker.controller !== null)
  await context.setOffline(true)
  await page.reload()
  await performance(page, 'Matches')
  await expect(page.getByText('3 scoring points', { exact: true })).toBeVisible()
  const original = (await stored(page)).performance.matches[0]
  expect(original.shots).toHaveLength(2); expect(original.aggregate.one.attempts).toBeNull()
  await page.getByRole('button', { name: 'Edit match', exact: true }).click()
  await dialog.getByText('Scoring: quick totals or individual shots', { exact: true }).click()
  page.once('dialog', d => d.accept())
  await dialog.getByRole('button', { name: 'Quick totals', exact: true }).click()
  await expect(dialog.getByLabel('One-point attempts', { exact: true })).toHaveValue('')
  await dialog.getByLabel('One-point attempts', { exact: true }).fill('2')
  await dialog.getByLabel('One-point conversions', { exact: true }).fill('1')
  await dialog.getByRole('button', { name: 'Update match', exact: true }).click()
  await expect(dialog).not.toBeVisible()
  const updated = (await stored(page)).performance.matches[0]
  expect(updated.scoringMode).toBe('Aggregate'); expect(updated.shots).toEqual([])
  page.once('dialog', d => d.accept())
  await page.getByRole('button', { name: 'Delete match', exact: true }).click()
  await expect(page.getByText('No match records yet', { exact: true })).toBeVisible()
  expect((await stored(page)).performance.matches).toEqual([])
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await context.setOffline(false)
})
