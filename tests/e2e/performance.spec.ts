test('incompatible protocols remain separate and results can be deleted without removing definitions', async ({ page }) => {
  test.setTimeout(120000)
  const data = createInitialData()
  data.performance.results = [testRecord(), testRecord({ id: 'test-2', date: '2025-05-01', attempts: [1.85, 1.8], value: 1.8 }), { ...testRecord({ id: 'test-3', attempts: [1.2, 1.1], value: 1.1 }), protocol: { ...testRecord().protocol, method: 'Handheld stopwatch' } }]
  await seed(page, data)
  await performance(page, 'Testing')
  await expect(page.getByRole('heading', { name: /^Comparison protocol/ })).toHaveCount(2)
  await expect(page.getByRole('img', { name: /10 m sprint; s/ })).toHaveCount(2)
  await expect(page.getByText('-0.1 s', { exact: true })).toBeVisible()
  await page.screenshot({ path: test.info().outputPath('test-protocols.png'), fullPage: true })
  page.once('dialog', d => d.accept())
  await page.getByRole('button', { name: 'Delete test 10 m sprint 2025-04-01', exact: true }).last().click()
  await expect(page.getByRole('heading', { name: /^Comparison protocol/ })).toHaveCount(1)
  expect((await stored(page)).performance.results).toHaveLength(2)
  await page.getByRole('navigation', { name: 'Performance sections' }).getByRole('button', { name: 'Definitions', exact: true }).click()
  await page.getByLabel('Enable 10 m sprint', { exact: true }).click()
  await expect(page.getByLabel('Enable 10 m sprint', { exact: true })).not.toBeChecked()
  await page.reload()
  await performance(page, 'Testing')
  await expect(page.getByRole('button', { name: 'Record selected test' })).toBeDisabled()
  await expect(page.getByRole('heading', { name: 'Comparison protocol 1' })).toBeVisible()
})

