test('failed storage writes keep the editor open and never claim success', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'View session', exact: true }).click()
  await page.getByRole('button', { name: 'Log this workout' }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('Actual minutes').fill('25')
  await dialog.getByLabel('Session effort (RPE)').selectOption('4')
  await dialog.getByRole('button', { name: 'Save workout', exact: true }).click()
  await expect(dialog.getByRole('alert')).toHaveText('Mark at least one set as performed before saving.')
  await dialog.getByRole('checkbox').first().check()
  await page.evaluate(() => { IDBObjectStore.prototype.put = () => { throw new DOMException('Storage full', 'QuotaExceededError') } })
  await dialog.getByRole('button', { name: 'Save workout', exact: true }).click()
  await expect(page.getByText('Could not save to this device.', { exact: false })).toBeVisible()
  await expect(dialog).toBeVisible()
  await expect(dialog.getByLabel('Actual minutes')).toHaveValue('25')
  await page.reload()
  const nav = page.getByRole('navigation', { name: test.info().project.name.startsWith('iPhone') ? 'Mobile navigation' : 'Main navigation', exact: true })
  await nav.getByRole('button', { name: 'Activity' }).click()
  await expect(page.getByText('No workouts logged yet.', { exact: false })).toBeVisible()
})
test('production app is installable and works offline after first load', async ({ page, context }) => {
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'A little better. Every day.' })).toBeVisible()
  await page.evaluate(async () => { await navigator.serviceWorker.ready })
  await page.reload()
  await page.waitForFunction(() => navigator.serviceWorker.controller !== null)
  const manifest = await (await page.request.get('/manifest.webmanifest')).json()
  expect(manifest.display).toBe('standalone')
  expect(manifest.icons.some((i: { sizes: string }) => i.sizes === '512x512')).toBe(true)
  await context.setOffline(true)
  await page.reload()
  await expect(page.getByRole('heading', { name: 'A little better. Every day.' })).toBeVisible()
  await expect(page.getByText('You’re offline.', { exact: false })).toBeVisible()
})
