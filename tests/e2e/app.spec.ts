import { test, expect } from '@playwright/test'
test('plan, log, persist, edit, export and delete a workout', async ({ page }) => {
  await page.goto('/')
  const nav = page.getByRole('navigation', { name: test.info().project.name.startsWith('iPhone') ? 'Mobile navigation' : 'Main navigation', exact: true })
  await expect(page.getByRole('heading', { name: 'A little better. Every day.' })).toBeVisible()
  await nav.getByRole('button', { name: 'Activity' }).click()
  await expect(page.getByText('No workouts logged yet.', { exact: false })).toBeVisible()
  await nav.getByRole('button', { name: 'Programme' }).click()
  await page.getByRole('button', { name: 'Add session', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('Session title', { exact: true }).fill('My pitch session')
  await dialog.getByLabel('Exercise name', { exact: true }).fill('Hand passing')
  await dialog.getByLabel('Reps, distance or time').fill('10 passes each side')
  await dialog.getByRole('button', { name: 'Save session', exact: true }).click()
  await expect(dialog).not.toBeVisible()
  await page.getByRole('button', { name: /My pitch session/ }).click()
  await page.getByRole('button', { name: 'Log this workout' }).click()
  await expect(dialog.getByLabel('Actual minutes')).toHaveValue('')
  await dialog.getByLabel('Hand passing set 1 done').check()
  await dialog.getByLabel('Hand passing set 1 reps').fill('10')
  await dialog.getByLabel('Actual minutes').fill('30')
  await dialog.getByLabel('Session effort (RPE)').selectOption('5')
  await dialog.getByLabel('How did it go?').fill('Practised both sides.')
  await dialog.getByRole('button', { name: 'Save workout', exact: true }).click()
  await expect(dialog).not.toBeVisible()
  await nav.getByRole('button', { name: 'Activity' }).click()
  await expect(page.getByText('Practised both sides.')).toBeVisible()
  await expect(page.getByText('1 / 3 sets performed · Partial session')).toBeVisible()
  await page.reload()
  await nav.getByRole('button', { name: 'Activity' }).click()
  await expect(page.getByText('Practised both sides.')).toBeVisible()
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Export data', exact: true }).click()
  expect((await download).suggestedFilename()).toMatch(/athlete-lab.*json/)
  await nav.getByRole('button', { name: 'Programme' }).click()
  await page.getByRole('button', { name: /My pitch session/ }).click()
  await page.getByRole('button', { name: 'Edit session', exact: true }).click()
  await dialog.getByLabel('Session title', { exact: true }).fill('Revised pitch session')
  await dialog.getByRole('button', { name: 'Save session', exact: true }).click()
  await page.getByRole('button', { name: /Revised pitch session/ }).click()
  page.once('dialog', d => d.accept())
  await page.getByRole('button', { name: 'Delete session', exact: true }).click()
  await nav.getByRole('button', { name: 'Activity' }).click()
  await expect(page.getByRole('heading', { name: 'My pitch session', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'View / edit log' }).click()
  await dialog.getByLabel('Actual minutes').fill('32')
  await dialog.getByRole('button', { name: 'Update workout' }).click()
  await expect(page.getByText(/32 min · RPE 5\/10/)).toBeVisible()
  page.once('dialog', d => d.accept())
  await page.getByRole('button', { name: 'Delete', exact: true }).click()
  await expect(page.getByText('No workouts logged yet.', { exact: false })).toBeVisible()
})
